-- INTEGERS
INT = integers
BIGINT = big integers
SMALLINT - TINYINT = small integers


-- DECIMALS
DECIMAL(ps) / NUMERIC(p,s) = exacts 
FLOAT / REAL = aproximate


-- BOOLEAN
BIT = 0 o 1


-- CHARACTER STRINGS (TEXT)

-- Non-Unicoide
CHAR(n) = fixed length
VARCHAR(n) = variable length
VARCHAR(MAX) = large TEXT

-- Unicoide
NVARCHAR(n) = fixed length
NVARCHAR(n) = variable length
NVARCHAR(MAX) = large text


-- DATE AND TIME
DATE = only date
TIME = only time
DATETIME = date and time (old)
DATETIEME2 = date and time
SMALLDATETIME = less precision


-- BINARY TYPES
BINARY(n) = fixed binary
VARBINARY(n) = variable binary 
VARBINARY(MAX) = large files


-- OTHER TYPES
MONEY / SMALLMONEY = currency
UNIQUEIDENTIFIER = GUID
XML = XML data
ROWVERSION = row version control
